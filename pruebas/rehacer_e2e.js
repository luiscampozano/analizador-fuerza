const { chromium } = require('playwright');
const B='http://localhost:8790', T=process.argv[2];
const ok=(c,m)=>console.log(c?'OK  ':'FAIL',m);
(async()=>{
  const br=await chromium.launch();
  const c=await br.newContext({viewport:{width:412,height:900}}); const p=await c.newPage(); const errs=[];
  p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>{if(m.type()==='error'&&!/gsi|accounts.google|Failed to load resource/.test(m.text()))errs.push(m.text())});
  p.on('dialog', d => { console.log('dialogo:', d.message()); d.accept(); });
  await p.addInitScript(()=>{localStorage.setItem('af_bienvenida','omitida');localStorage.setItem('af_ej','sentadilla');localStorage.setItem('af_calidad','rapida');});
  await p.goto(B+'/index.html'); await p.waitForTimeout(1200);
  await p.setInputFiles('#input-video', T+'/sq.mp4');
  await p.evaluate(()=>{const v=(i,x)=>{document.getElementById(i).value=x;};v('in-peso','100');v('in-altura','1.68');v('in-calidad','rapida');document.getElementById('in-video').checked=true;document.getElementById('btn-analizar').click();});
  await p.waitForFunction(()=>document.getElementById('r-reps').textContent!=='--' && document.getElementById('v-resultados').classList.contains('active'),null,{timeout:1500000});
  const n0=+(await p.textContent('#r-reps')); ok(n0>=2,'análisis con video hecho, reps='+n0);
  const tam0=await p.evaluate(async()=>{const al=await import('/js/almacen.js');const h=JSON.parse(localStorage.getItem('af_historial_v1'));const v=await al.leerVideo(h[h.length-1].id);return v?v.blob.size:0;});
  ok(tam0>0,'video guardado ('+tam0+' bytes)');
  await p.evaluate(()=>document.getElementById('btn-corregir').click()); await p.waitForTimeout(300);
  await p.click('#corr-cuerpo [data-tope] >> nth=0');
  await p.evaluate(()=>{const x=document.getElementById('corr-enviar'); if (x) x.checked=false;});
  await p.click('#corr-guardar');
  await p.waitForTimeout(2000);
  await p.waitForFunction(()=>document.getElementById('v-resultados').classList.contains('active'),null,{timeout:1500000});
  await p.waitForTimeout(1500);
  const est=await p.evaluate(async()=>{const al=await import('/js/almacen.js');const h=JSON.parse(localStorage.getItem('af_historial_v1'));const id=h[h.length-1].id;const v=await al.leerVideo(id);const inf=await al.leerInforme(id);return {tam:v?v.blob.size:0,videoCorregido:inf.videoCorregido,reps:inf.reps.length, boton:getComputedStyle(document.getElementById('btn-rehacer')).display};});
  ok(+(await p.textContent('#r-reps'))===n0-1,'informe con '+(n0-1)+' reps: '+(await p.textContent('#r-reps')));
  ok(est.videoCorregido===true && est.tam>0 && est.tam!==tam0,'video rehecho ('+JSON.stringify(est)+')');
  ok(est.boton==='none','botón Actualizar oculto tras rehacer');
  await p.evaluate(()=>{const v=document.getElementById('r-video'); v.currentTime=Math.max(0,v.duration-0.1);}); await p.waitForTimeout(2000);
  await p.locator('#r-video').screenshot({path:T+'/rehacer_final.png'});
  console.log('errores',errs); await br.close();
})();
